interface Props {
  fixture: MatchFixture;
  focus?: MatchFocus;
  timeMs: number;
  playback: PlaybackPhase;
  audience: Audience;
  onAudience: (audience: Audience) => void;
  onPause: () => void;
  onReplayFrom: (timeMs: number) => void;
  /** Every explanation asked for in this match, kept by the viewer so leaving the panel never loses one. */
  saved: SavedExplanation[];
  /** The saved explanation on screen, if any. */
  shownId: string | null;
  onSaved: (explanation: SavedExplanation) => void;
  onShow: (id: string | null) => void;
}

/** One answer from the explanation service, and the playback time and audience it was asked for. */
export interface SavedExplanation {
  id: string;
  atMs: number;
  audience: Audience;
  result: ExplainSuccess;
  /** Set on automatic insights: the key moment it explains (atMs is that moment's time). */
  eventId?: string;
}

export const audienceName = (audience: Audience) => (audience === "analyst" ? "Analyst" : "Casual Fan");

/**
 * Saved explanations that only use evidence up to `timeMs`, newest first. One
 * asked for later in the match describes play not reached yet, so it stays
 * hidden until playback gets there again.
 */
export function explanationsUpTo(saved: readonly SavedExplanation[], timeMs: number): SavedExplanation[] {
  return saved.filter((s) => s.atMs <= timeMs).sort((a, b) => b.atMs - a.atMs);
}

const AUDIENCE_OPTIONS = [
  ["casual", "Casual Fan", "Plain language: what happened and why it matters", "users"],
  ["analyst", "Analyst", "Tactical detail: shape, passing and positions", "bars"],
] as const;

/** Casual Fan / Analyst switch, shared by the panel and the recap. */
export function AudienceSwitch({ audience, onAudience, className, withIcons = false }:
  { audience: Audience; onAudience: (a: Audience) => void; className?: string; withIcons?: boolean }) {
  return (
    <div className={`seg${className ? ` ${className}` : ""}`} role="group" aria-label="Explanation audience">
      {AUDIENCE_OPTIONS.map(([id, text, hint, icon]) => (
        <button type="button" key={id} title={hint} aria-pressed={audience === id} onClick={() => onAudience(id)}>
          {withIcons && <Icon name={icon} size={18} />}
          {text}
        </button>
      ))}
    </div>
  );
}

/** Where the evidence stops, in the viewer's terms. */
function scopeText(playback: PlaybackPhase, timeMs: number) {
  if (playback === "ended") return "Full time · evidence from the whole match";
  if (playback === "playing") return `Live · evidence up to ${formatClock(timeMs)}`;
  if (playback === "ready") return "Kick-off · no play yet";
  return `Paused at ${formatClock(timeMs)} · evidence up to here only`;
}

/** "Live insights": the docked panel beside the pitch, automatic insights first, then asking about any moment. */
export function ExplanationPanel(props: Props) {
  const supported = matchReferenceOf(props.fixture, sampleFixture.matchId) !== null;
  const allowed = useExplanationAccess();
  return (
    <ExplanationSchedulerScope>
      <section className="explain" aria-labelledby="explain-title">
        <div className="explain__head">
          <h2 id="explain-title">Live insights</h2>
          <span className="ai-tag" title="Generated by an AI model from synthetic match data">
            <Icon name="spark" size={13} />
            AI
          </span>
        </div>
        <p className="explain__scope">{scopeText(props.playback, props.timeMs)}</p>
        <AudienceSwitch audience={props.audience} onAudience={props.onAudience} className="explain__audience" />
        {!allowed && supported && <p className="explain__note" role="status">{LOCKED_HINT}</p>}
        {supported && <LiveInsights fixture={props.fixture} timeMs={props.timeMs} playback={props.playback} audience={props.audience}
          focus={props.focus} saved={props.saved} onSaved={props.onSaved} onReplayFrom={props.onReplayFrom} />}
        <section className="explain__ask" aria-labelledby="explain-ask-title">
          <h3 id="explain-ask-title" className="explain__section">Ask about any moment</h3>
          {(props.focus?.teamId || props.focus?.playerId) && <p className="explain__scope">Explains the whole moment, including both teams.</p>}
          {/* Keyed by match and audience only: the request must survive the clock ticking. */}
          <ExplanationRequest key={`${props.fixture.matchId}:${props.audience}`} {...props} />
        </section>
      </section>
    </ExplanationSchedulerScope>
  );
}

function ExplanationRequest({ fixture, timeMs, playback, audience, onAudience, onPause, onReplayFrom, saved, shownId, onSaved, onShow }: Props) {
  const scheduler = useExplanationScheduler();
  const [pendingAt, setPendingAt] = useState<number | null>(null);
  // False while the request waits for another one (an automatic insight) to finish.
  const [sent, setSent] = useState(false);
  // Only an answer for the selected audience shows; the others stay in the history.
  const answer = saved.find((s) => s.id === shownId && s.audience === audience) ?? null;
  const [error, setError] = useState("");
  const pending = useRef<AbortController | null>(null);
  useEffect(() => () => { pending.current?.abort(); }, []);
  const supported = matchReferenceOf(fixture, sampleFixture.matchId) !== null;
  const allowed = useExplanationAccess();
  const allowedRef = useRef(allowed);
  allowedRef.current = allowed;
  const timeRef = useRef(timeMs);
  timeRef.current = timeMs;
  // Automatic insights live in the feed above; this part only shows what was asked for here.
  const asked = saved.filter((s) => !s.eventId);

  // Citation replay has the same cutoff as every other backward seek. Keep the
  // selection saved so it can reappear when playback reaches its cutoff again.
  const visible = answer && timeMs >= answer.atMs ? answer : null;
  // Seeking back past an in-flight request's time abandons it.
  useEffect(() => {
    if (pendingAt !== null && timeMs < pendingAt) cancel();
  }, [timeMs, pendingAt]);
  // Locking or expiry abandons the request; saved answers stay.
  useEffect(() => {
    if (!allowed) cancel();
  }, [allowed]);

  function cancel() {
    pending.current?.abort();
    pending.current = null;
    setPendingAt(null);
  }

  async function explain() {
    if (pending.current || !allowed) return;
    const atMs = timeMs;
    onPause();
    const controller = new AbortController();
    pending.current = controller;
    setPendingAt(atMs);
    setSent(false);
    setError("");
    try {
      // Not sent once playback is back before its time or access is locked; the effects above then cancel it.
      const wanted = () => allowedRef.current && timeRef.current >= atMs;
      const result = await scheduler.schedule({ priority: "manual", signal: controller.signal, wanted, onStart: () => setSent(true) },
        () => requestExplanation(fixture, sampleFixture.matchId, atMs, audience, controller.signal, fetch, "moment", delay => scheduler.defer(delay)));
      if (!controller.signal.aborted && timeRef.current >= atMs && allowedRef.current) {
        const id = `${audience}-${Math.floor(atMs)}-${asked.length}`;
        onSaved({ id, atMs, audience, result });
        onShow(id);
      }
    } catch (e) {
      if (!controller.signal.aborted) setError(e instanceof Error && !(e instanceof TypeError || e instanceof SyntaxError)
        ? e.message : "The explanation could not be loaded. Check your connection and try again.");
    } finally {
      if (!controller.signal.aborted) { pending.current = null; setPendingAt(null); }
    }
  }

  function open(s: SavedExplanation) {
    if (s.audience !== audience) onAudience(s.audience);
    onShow(s.id);
  }

  function replay(t: number) {
    const from = Math.max(0, t - 3_000);
    onReplayFrom(from);
  }

  const loading = pendingAt !== null;
  const fallback = visible?.result.verification?.outcome === "fallback";
  const stale = visible !== null && Math.floor(timeMs) > Math.floor(visible.atMs);
  // Only offer to pause when there is something to pause.
  const label = loading ? "Explaining…" : error ? "Try again"
    : fallback ? (showsMatchFacts(visible!.result) ? "Get AI explanation" : "Try again")
    : playback === "playing" ? "Pause and explain" : "Explain this moment";
  const explanation = visible?.result.explanation;
  const history = explanationsUpTo(asked, timeMs).filter((s) => s.id !== visible?.id);

  return <>
    <button className="btn btn--ghost btn--block explain__go" type="button" disabled={loading || !supported || !allowed} onClick={explain}>
      {loading ? <span className="spinner spinner--small" aria-hidden="true" /> : <Icon name={playback === "playing" ? "pause" : "spark"} size={18} />}
      {label}
    </button>

    {!supported && <p className="explain__note">Explanations are unavailable for this match. Try the demo or generate a new match.</p>}
    {pendingAt !== null && <div className="explain__loading" role="status">
      <div className="explain__status">
        <span>{sent ? `Reading the evidence up to ${formatClock(pendingAt)} and checking the answer…`
          : `Queued to explain ${formatClock(pendingAt)}. Waiting for the next request slot…`}</span>
        <button className="btn btn--ghost btn--small" type="button" onClick={cancel}>Cancel</button>
      </div>
      <div className="skeleton" aria-hidden="true"><span /><span /><span /><span /></div>
    </div>}
    {error && <p className="explain__error" role="alert"><Icon name="warning" size={16} />{error}</p>}
    {!visible && !loading && !error && supported && (
      <p className="explain__empty">Stop on any other moment and ask why it matters. Explanations only use what has happened so far.</p>
    )}

    {visible && explanation && <article className={`explain__answer${showsMatchFacts(visible.result) ? " explain__answer--facts" : ""}`} aria-live="polite">
      <div className="explain__meta">
        <span>{audienceName(audience)} · explained at {formatClock(visible.atMs)}</span>
        <button className="btn btn--ghost btn--icon btn--small" type="button" aria-label="Close explanation"
          title="Close. It stays under Your explanations."
          onClick={() => onShow(null)}>
          <Icon name="close" size={16} />
        </button>
      </div>
      {stale && <p className="explain__notice">Play has moved on since this explanation. Explain again for the current moment.</p>}
      <ExplanationBody fixture={fixture} result={visible.result} audience={audience} onReplay={replay} />
    </article>}

    {history.length > 0 && <section className="explain__history" aria-labelledby="explain-history-title">
      <h4 id="explain-history-title" className="explain__section">Your explanations</h4>
      <ul>
        {history.map((s) => (
          <li key={s.id}>
            <button type="button" className={`explain__saved${showsMatchFacts(s.result) ? " explain__saved--facts" : ""}`} onClick={() => open(s)}>
              <span className="explain__saved-meta"><time>{formatClock(s.atMs)}</time> · {audienceName(s.audience)}
                {showsMatchFacts(s.result) && <MatchFactsChip />}</span>
              <span className="explain__saved-title">{savedTitle(s)}</span>
            </button>
          </li>
        ))}
      </ul>
    </section>}
  </>;
}

/** One checked answer: headline, text, the evidence to replay, how it was checked and its limits. */
export function ExplanationBody({ fixture, result, audience, onReplay, onRetry }:
  { fixture: MatchFixture; result: ExplainSuccess; audience: Audience; onReplay: (timeMs: number) => void;
    /** Shown on an unverified answer when the surrounding view has no retry of its own. */
    onRetry?: () => void }) {
  const recorded = result.verification?.outcome === "fallback" ? result.recordedSummary : undefined;
  const explanation = recorded ?? result.explanation;
  const allowed = useExplanationAccess();
  const outcome = result.verification?.outcome;
  const fallback = outcome === "fallback";
  const evidence = fallback && !recorded ? [] : citedEvidence(fixture, explanation);
  return <>
    {fallback && !recorded ? <>
      <h3 className="explain__headline">{FALLBACK_TITLE}</h3>
      <p className="explain__body">
        Every explanation is checked against what has happened in the match so far. This one included
        claims the match data could not back up, so it is not shown. Trying again gives a fresh answer.
      </p>
      {onRetry && <button type="button" className="btn btn--ghost btn--small" disabled={!allowed} onClick={onRetry}>Try again</button>}
    </> : <>
      {recorded && <MatchFactsChip placement="block" />}
      <h3 className="explain__headline">{explanation.headline}</h3>
      <p className="explain__body">{explanation.explanation}</p>
      {recorded && <div className="explain__facts-note">
        <p className="explain__facts-text">{MATCH_FACTS_NOTE}</p>
        {onRetry && <button type="button" className="btn btn--accent btn--small" disabled={!allowed} onClick={onRetry}>
          <Icon name="spark" size={14} />Get AI explanation</button>}
      </div>}
      {evidence.length > 0 && <>
        <h4 className="explain__section">See the evidence</h4>
        <EvidenceCards fixture={fixture} items={evidence} onReplay={onReplay} />
      </>}
    </>}
    <CheckRow outcome={outcome} status={explanation.status} atMs={result.timeMs} recorded={!!recorded} />
    {(!fallback || recorded) && <details className="explain__details" open={audience === "analyst"}>
      <summary>Facts, reading and limits<Icon name="chevron" size={16} className="explain__chevron" /></summary>
      <ExplanationDetails explanation={explanation} fixture={fixture} onReplay={onReplay} />
    </details>}
    <p className="explain__disclaimer">{recorded ? "Built from synthetic match events; no AI interpretation." : "AI explanation. Automated checks reduce mistakes; citations identify evidence and do not prove a claim."}</p>
  </>;
}

/** True when a result shows recorded match facts in place of an AI answer that failed its checks. */
export const showsMatchFacts = (result: ExplainSuccess) =>
  result.verification?.outcome === "fallback" && result.recordedSummary !== undefined;

/** Why recorded match facts are shown, said the same way wherever they appear. */
export const MATCH_FACTS_NOTE = "No AI explanation passed the checks for this moment. These facts come straight from the recorded match events.";

/**
 * Marks recorded match facts wherever they are listed or shown, with the list
 * icon rather than the AI spark, so they never read as an AI explanation.
 */
export function MatchFactsChip({ placement = "trail" }: { placement?: "block" | "lead" | "trail" }) {
  return <span className={`facts-chip facts-chip--${placement}`}><Icon name="list" size={12} />Match facts, not AI</span>;
}

/** What an answer that failed its checks is called wherever it is listed or shown. */
export const FALLBACK_TITLE = "This explanation didn't pass our checks";

/** The headline to list a saved explanation by; an unverified one gets a plain label instead of its text. */
export const savedTitle = (s: SavedExplanation) =>
  s.result.verification?.outcome === "fallback" ? s.result.recordedSummary?.headline ?? FALLBACK_TITLE : s.result.explanation.headline;

/** "Evidence checked · Based on events up to …", or why it is not. */
export function CheckRow({ outcome, status, atMs, label, recorded = false }:
  { outcome: ExplainSuccess["verification"]["outcome"] | undefined; status: string; atMs: number; label?: string;
    /** Showing the recorded match summary in place of an unverified AI answer. */
    recorded?: boolean }) {
  return (
    <div className="check-row">
      {recorded ? <span className="check check--info"><Icon name="info" size={16} />Recorded match facts</span>
        : outcome === "fallback" ? <span className="check check--warn"><Icon name="warning" size={16} />Not shown: failed checks</span>
        : outcome === "insufficient-evidence" || status === "insufficient-evidence"
          ? <span className="check check--info"><Icon name="info" size={16} />Not enough evidence</span>
          : <span className="check"><span className="check__badge"><Icon name="check" size={14} /></span>Evidence checked</span>}
      <span>{label ?? `Based on events up to ${formatClock(atMs)}`}</span>
    </div>
  );
}
